export interface NFTMetadata {
  name: string;
  description: string;
  image: string; // IPFS hash
  attributes: Array<{
    trait_type: string;
    value: string | number;
  }>;
  birthData: {
    date: string;
    time: string;
    place: string;
  };
}

export interface NFTCertificate {
  tokenId: string;
  owner: string;
  metadata: NFTMetadata;
  transactionHash: string;
  ipfsUrl: string;
}

